/* ==========================================================================
   Primitives
   --------------------------------------------------------------------------
   Everything the interface is built from. Variants exist because they mean
   something, not to offer choice: `primary` is the one action on a screen,
   `impact` is reserved for contributions, and `ghost` is for everything that
   should not compete.
   ========================================================================== */

export function cx(...values: (string | false | null | undefined)[]): string {
  return values.filter(Boolean).join(' ');
}

/* ------------------------------- Button ---------------------------------- */

type ButtonVariant = 'primary' | 'secondary' | 'ghost' | 'impact' | 'danger' | 'inverted';
type ButtonSize = 'sm' | 'md' | 'lg';

const BUTTON_BASE =
  'inline-flex items-center justify-center gap-2 font-semibold rounded-[--radius-field] transition-all duration-200 ' +
  'disabled:opacity-45 disabled:pointer-events-none select-none whitespace-nowrap';

const BUTTON_VARIANTS: Record<ButtonVariant, string> = {
  primary: 'bg-ink text-white hover:bg-ink-soft active:scale-[0.985] shadow-[0_1px_2px_rgba(14,17,19,0.16)]',
  secondary: 'bg-white text-ink border border-line-strong hover:border-ink hover:bg-sand active:scale-[0.985]',
  ghost: 'text-ink-soft hover:text-ink hover:bg-sand',
  impact: 'bg-clay-500 text-white hover:bg-clay-600 active:scale-[0.985]',
  danger: 'bg-white text-danger border border-danger/25 hover:bg-danger-soft',
  inverted: 'bg-white text-ink hover:bg-white/90 active:scale-[0.985]',
};

// Touch targets stay at 44px and up on the smallest size — this is a phone-first
// product and buttons get tapped with thumbs.
const BUTTON_SIZES: Record<ButtonSize, string> = {
  sm: 'h-10 px-4 text-[0.8125rem]',
  md: 'h-12 px-6 text-sm',
  lg: 'h-14 px-8 text-[0.9375rem]',
};

interface ButtonBaseProps {
  variant?: ButtonVariant;
  size?: ButtonSize;
  full?: boolean;
  className?: string;
  children: ReactNode;
}

export function Button({
  variant = 'primary',
  size = 'md',
  full,
  className,
  children,
  ...props
}: ButtonBaseProps & ButtonHTMLAttributes<HTMLButtonElement>) {
  return (
    <button
      className={cx(BUTTON_BASE, BUTTON_VARIANTS[variant], BUTTON_SIZES[size], full && 'w-full', className)}
      {...props}
    >
      {children}
    </button>
  );
}

export function ButtonLink({
  variant = 'primary',
  size = 'md',
  full,
  className,
  href,
  children,
  ...props
}: ButtonBaseProps & { href: string } & Omit<AnchorHTMLAttributes<HTMLAnchorElement>, 'href'>) {
  return (
    <Link
      href={href}
      className={cx(BUTTON_BASE, BUTTON_VARIANTS[variant], BUTTON_SIZES[size], full && 'w-full', className)}
      {...props}
    >
      {children}
    </Link>
  );
}

