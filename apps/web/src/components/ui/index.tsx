/* ------------------------------- Progress -------------------------------- */

/**
 * A funding meter. The number is always written next to the bar — a bar alone
 * asks the reader to estimate, and with money that is not good enough.
 */
export function Progress({
  percent,
  tone = 'impact',
  size = 'md',
  className,
  label,
}: {
  percent: number;
  tone?: 'impact' | 'brand' | 'neutral';
  size?: 'sm' | 'md';
  className?: string;
  label?: string;
}) {
  const clamped = Math.max(0, Math.min(100, Math.round(percent)));
  const fill =
    tone === 'impact' ? 'bg-clay-500' : tone === 'brand' ? 'bg-acacia-600' : 'bg-ink';

  return (
    <div
      className={cx('w-full', className)}
      role="progressbar"
      aria-valuenow={clamped}
      aria-valuemin={0}
      aria-valuemax={100}
      aria-label={label ?? `${clamped}% funded`}
    >
      <div className={cx('w-full overflow-hidden rounded-full bg-sand-deep', size === 'sm' ? 'h-1.5' : 'h-2')}>
        <div
          className={cx('h-full rounded-full transition-[width] duration-700', fill)}
          style={{ width: `${clamped}%` }}
        />
      </div>
    </div>
  );
}

/* -------------------------------- Avatar --------------------------------- */

/**
 * Initial-based avatars.
 *
 * Demo accounts deliberately have no photograph — using stock portraits of real
 * people as stand-ins for fictional travellers misrepresents them. The tint is
 * derived from the name so a person keeps the same colour everywhere.
 */
const AVATAR_TINTS = [
  'bg-acacia-100 text-acacia-700',
  'bg-clay-100 text-clay-700',
  'bg-sand-deep text-ink-soft',
  'bg-[#e3e9ef] text-[#2f4a63]',
  'bg-[#eae4f0] text-[#4d3c63]',
];

function tintFor(name: string): string {
  let hash = 0;
  for (let i = 0; i < name.length; i += 1) hash = (hash * 31 + name.charCodeAt(i)) % 997;
  return AVATAR_TINTS[hash % AVATAR_TINTS.length];
}

const AVATAR_SIZES = {
  xs: 'h-7 w-7 text-[0.625rem]',
  sm: 'h-9 w-9 text-[0.6875rem]',
  md: 'h-11 w-11 text-xs',
  lg: 'h-16 w-16 text-base',
  xl: 'h-24 w-24 text-2xl',
} as const;

export function Avatar({
  name,
  src,
  size = 'md',
  className,
  ring,
}: {
  name: string;
  src?: string | null;
  size?: keyof typeof AVATAR_SIZES;
  className?: string;
  ring?: boolean;
}) {
  const classes = cx(
    'inline-flex shrink-0 items-center justify-center rounded-full font-bold tracking-wide overflow-hidden',
    AVATAR_SIZES[size],
    ring && 'ring-2 ring-white',
    className,
  );

  if (src) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src={src} alt={name} className={cx(classes, 'object-cover')} />;
  }

  return (
    <span className={cx(classes, tintFor(name))} aria-label={name} title={name}>
      {initials(name)}
    </span>
  );
}

/** Overlapping avatars for "who else is coming". */
export function AvatarStack({
  people,
  max = 5,
  size = 'sm',
}: {
  people: { id: string; name: string; avatarUrl?: string | null }[];
  max?: number;
  size?: keyof typeof AVATAR_SIZES;
}) {
  const shown = people.slice(0, max);
  const remaining = people.length - shown.length;

  return (
    <div className="flex items-center">
      <div className="flex -space-x-2.5">
        {shown.map((person) => (
          <Avatar key={person.id} name={person.name} src={person.avatarUrl} size={size} ring />
        ))}
      </div>
      {remaining > 0 && (
        <span className="ml-3 text-[0.8125rem] font-medium text-ink-muted">+{remaining} more</span>
      )}
    </div>
  );
}

