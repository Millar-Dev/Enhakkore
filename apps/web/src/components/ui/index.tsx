export function RatingLine({
  rating,
  count,
  className,
}: {
  rating: number | null;
  count: number;
  className?: string;
}) {
  if (rating === null || count === 0) {
    return <span className={cx('text-[0.8125rem] text-ink-faint', className)}>No reviews yet</span>;
  }
  return (
    <span className={cx('inline-flex items-center gap-1.5 text-[0.8125rem]', className)}>
      <svg width="14" height="14" viewBox="0 0 20 20" fill="currentColor" className="text-clay-500">
        <path d="M10 1.5l2.47 5.36 5.78.66-4.3 3.96 1.16 5.77L10 14.4l-5.11 2.85 1.16-5.77-4.3-3.96 5.78-.66z" />
      </svg>
      <span className="font-semibold text-ink">{rating.toFixed(1)}</span>
      <span className="text-ink-muted">({count})</span>
    </span>
  );
}

