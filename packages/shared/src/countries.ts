const BY_CODE = new Map(COUNTRIES.map((country) => [country.code, country]));

export function countryByCode(code: string | null | undefined): CountryInfo | null {
  if (!code) return null;
  return BY_CODE.get(code.toUpperCase()) ?? null;
}
